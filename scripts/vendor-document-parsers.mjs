import { copyFile, mkdir, readFile, readdir, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = dirname(fileURLToPath(new URL("../package.json", import.meta.url)));
const vendorDirectory = join(root, "assets", "document-parsers");
const lockfile = JSON.parse(
  await readFile(join(root, "package-lock.json"), "utf8")
);

const parserAssets = [
  {
    packagePath: "node_modules/pdfjs-dist/build/pdf.min.mjs",
    vendorName: "pdf.min.mjs"
  },
  {
    packagePath: "node_modules/pdfjs-dist/build/pdf.worker.min.mjs",
    vendorName: "pdf.worker.min.mjs"
  },
  {
    packagePath: "node_modules/jszip/dist/jszip.min.js",
    vendorName: "jszip.min.js"
  }
];

await mkdir(vendorDirectory, { recursive: true });

for (const asset of parserAssets) {
  await copyFile(
    join(root, asset.packagePath),
    join(vendorDirectory, asset.vendorName)
  );
  console.log(`vendored ${asset.vendorName}`);
}

const installedPackages = Object.entries(lockfile.packages)
  .filter(([packagePath]) => packagePath.startsWith("node_modules/"))
  .map(([packagePath, metadata]) => ({
    directory: join(root, packagePath),
    name: packagePath.slice("node_modules/".length),
    version: metadata.version,
    declaredLicense: metadata.license
  }))
  .sort((left, right) => left.name.localeCompare(right.name));

async function readPackageLicense(packageMetadata) {
  let entries;
  try {
    entries = await readdir(packageMetadata.directory, { withFileTypes: true });
  } catch (error) {
    if (error.code === "ENOENT") {
      return null;
    }
    throw error;
  }

  const licenseEntry = entries
    .filter((entry) => entry.isFile())
    .map((entry) => entry.name)
    .sort()
    .find((name) => /^(licen[cs]e|copying|notice)(?:[._-].*|$)/i.test(name));

  let licenseText;
  if (licenseEntry) {
    licenseText = await readFile(
      join(packageMetadata.directory, licenseEntry),
      "utf8"
    );
  } else if (packageMetadata.name === "isarray") {
    const readme = await readFile(
      join(packageMetadata.directory, "README.md"),
      "utf8"
    );
    const licenseSection = readme.indexOf("## License");
    if (licenseSection === -1) {
      throw new Error("isarray README does not contain its license section");
    }
    licenseText = readme.slice(licenseSection);
  } else {
    throw new Error(`No license text found for ${packageMetadata.name}`);
  }

  if (packageMetadata.name === "jszip") {
    licenseText = licenseText.split(/\nGPL version 3\n/i)[0];
  }

  return [
    `${packageMetadata.name} ${packageMetadata.version}`,
    `Declared license: ${packageMetadata.declaredLicense ?? "not specified"}`,
    "",
    licenseText.trim()
  ].join("\n");
}

const packageLicenses = [];
for (const packageMetadata of installedPackages) {
  const license = await readPackageLicense(packageMetadata);
  if (license) {
    packageLicenses.push(license);
  }
}

const licenseInventory = [
  "Nabu document parser third-party licenses",
  "Generated by npm run prepare:assets. Do not edit directly.",
  "Only packages installed for the browser parser asset build are included.",
  "",
  packageLicenses.join("\n\n========================================\n\n"),
  ""
].join("\n");

await writeFile(
  join(vendorDirectory, "THIRD_PARTY_LICENSES.txt"),
  licenseInventory,
  "utf8"
);
console.log("generated THIRD_PARTY_LICENSES.txt");
